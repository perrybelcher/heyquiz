const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
require.extensions['.ts'] = (m, f) => m._compile(ts.transpileModule(fs.readFileSync(f, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true } }).outputText, f);
const { FormSchema } = require('../lib/schema.ts');
const { evaluateMarketing } = require('../lib/marketing.ts');
const { setBasicAssociation, removeBasicCategory } = require('../lib/basic-editing.ts');
const form = FormSchema.parse({id:'test',title:'Test',mode:'survey',quizType:'product_finder',questions:[{id:'q',type:'multiple_choice',title:'Need?',options:[{id:'a',label:'Yes'},{id:'b',label:'No'}]}],marketing:{kind:'product_finder',outcomes:[{id:'one',title:'One'},{id:'two',title:'Two'}],rules:[{id:'unrelated',questionId:'q',answerId:'b',targetId:'two',points:7,reason:'Keep me'}]}});
let edited = setBasicAssociation(form,'q','a','one','5');
edited = setBasicAssociation(edited,'q','a','two','3');
assert.equal(evaluateMarketing(edited,{q:'a'}).outcomeId,'one');
assert.equal(edited.marketing.rules.length,3);
const firstId=edited.marketing.rules.find(r=>r.targetId==='one').id;
edited=setBasicAssociation(edited,'q','a','one','exclude');
assert.equal(evaluateMarketing(edited,{q:'a'}).outcomeId,'two');
assert.equal(edited.marketing.rules.find(r=>r.targetId==='one').id,firstId);
assert.equal(edited.marketing.rules.find(r=>r.id==='unrelated').reason,'Keep me');
edited=setBasicAssociation(edited,'q','a','one','');
assert.equal(edited.marketing.rules.length,2);
assert.equal(form.marketing.rules.length,1);
for(const value of ['-1','101','no']) assert.throws(()=>setBasicAssociation(form,'q','a','one',value));
assert.throws(()=>setBasicAssociation(form,'q','a','missing','3'));
const card=FormSchema.parse({...form,quizType:'scorecard',marketing:{kind:'scorecard',categories:[{id:'c',title:'Category'}]}});
const zero=setBasicAssociation(setBasicAssociation(card,'q','b','c','10'),'q','a','c','0');
assert.equal(zero.marketing.rules.find(r=>r.answerId==='a').points,0);
assert.equal(evaluateMarketing(zero,{q:'a'}).categories[0].answered,1);
const blank=setBasicAssociation(zero,'q','a','c','');
assert.equal(evaluateMarketing(blank,{q:'a'}).categories[0].answered,0);
assert.throws(()=>setBasicAssociation(card,'q','a','c','exclude'));
const withSection={...zero,marketing:{...zero.marketing,resultSections:[{id:'section',type:'text',title:'Category advice',body:'',url:'',label:'',condition:{type:'score',categoryId:'c',min:0,max:100}}]}};
const removed=removeBasicCategory(withSection,'c');
assert.equal(removed.marketing.categories.length,0);
assert.equal(removed.marketing.rules.length,0);
assert.equal(removed.marketing.resultSections.length,0);
console.log('PASS Basic inline associations: multiple targets, exclusions, stable IDs, neutral vs scored zero, boundaries and category dependency cleanup');
