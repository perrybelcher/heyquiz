const {chromium}=require('playwright'),assert=require('node:assert/strict');
(async()=>{const browser=await chromium.launch({channel:'chrome'});try{
 const page=await browser.newPage({viewport:{width:1440,height:1000}});const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto((process.env.BASE_URL||'http://127.0.0.1:3162')+'/templates');
    await page.getByRole('button',{name:'Browse additional existing templates',exact:true}).click();
 await page.getByRole('status').filter({hasText:'43 templates found'}).waitFor();
 assert.equal(await page.getByRole('button').filter({hasText:'Preview template'}).count(),12);
 await page.getByRole('button',{name:/Show more templates/}).click();
 assert.equal(await page.getByRole('button').filter({hasText:'Preview template'}).count(),24);
 await page.getByRole('combobox',{name:'Industry',exact:true}).selectOption('Food & drink');
 await page.getByRole('status').filter({hasText:'3 templates found'}).waitFor();
 await page.getByRole('combobox',{name:'Quiz goal'}).selectOption('Product finder');
 await page.getByRole('status').filter({hasText:'2 templates found'}).waitFor();
 await page.getByRole('textbox',{name:'Search templates'}).fill('nothingmatches');
 await page.getByRole('heading',{name:'No templates match those filters yet.'}).waitFor();
 await page.getByRole('button',{name:'Show all templates',exact:true}).click();
 await page.getByRole('textbox',{name:'Search templates'}).fill('coffee');
 await page.getByRole('button',{name:/Find your coffee style/}).click();
 await page.getByRole('region',{name:'Template details'}).waitFor();
 await page.waitForFunction(()=>document.activeElement?.getAttribute('aria-label')==='Template details');
 await page.keyboard.press('Escape');
 await page.getByRole('region',{name:'Template details'}).waitFor({state:'detached'});
 assert.equal(await page.getByRole('region',{name:'Template details'}).count(),0);
 assert.equal(await page.getByRole('button',{name:/Find your coffee style/}).evaluate(el=>el===document.activeElement),true);
 await page.getByRole('button',{name:'Clear filters',exact:true}).click();
 await page.screenshot({path:'/tmp/pippi-template-library-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('textbox',{name:'Search templates'}).fill('coffee');
 await page.getByRole('button',{name:/Find your coffee style/}).click();
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'/tmp/pippi-template-library-mobile.png',fullPage:true});
 await page.getByRole('button',{name:'Use this template',exact:true}).click();
 await page.getByRole('heading',{name:'Give your quiz a clear promise.',exact:true}).waitFor();
 const draft=await page.evaluate(()=>JSON.parse(localStorage.getItem('heyquiz-draft:'+localStorage.getItem('pippi-guest-draft'))));
 assert.equal(draft.title,'Find your coffee style');assert.equal(draft.questions.length,5);assert.equal(draft.marketing.outcomes.length,3);assert.equal(draft.capture.required,false);
 assert.deepEqual(errors,[]);console.log('PASS search, combined filters, pagination, empty state, keyboard focus, mobile layout, coffee draft creation, no page errors');
}finally{await browser.close();}})().catch(e=>{console.error(e);process.exitCode=1;});
