// Compiled local application, isolated synthetic records, no hosted providers.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.TEST_BASE_URL, artifacts = process.env.ARTIFACT_DIR;
assert.match(base || '', /^http:\/\/127\.0\.0\.1:\d+$/);
assert.ok(process.env.HEYQUIZ_DATA_DIR && artifacts, 'Explicit isolated records and artifacts required');
fs.mkdirSync(artifacts, { recursive: true });
const headers = { Origin: base }, id = `qa-usability-${Date.now()}`;
let browser, context;
(async () => {
  try {
    browser = await chromium.launch({ channel: 'chrome', headless: true });
    context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    context.setDefaultTimeout(15000);
    const anonymous = await context.request.get(`${base}/reports/${id}`, { maxRedirects: 0 });
    assert.equal(anonymous.status(), 307, 'Report requires authentication');
    assert.equal((await context.request.post(base + '/api/auth', { headers, data: { local: true } })).status(), 200);
    assert.equal((await context.request.get(`${base}/reports/not-owned`)).status(), 404, 'Unknown or unowned quiz is hidden');
    const created = await context.request.post(base + '/api/forms', { headers, data: { id, title: 'QA Usability Choice', mode: 'survey', questions: [{ id:'q1', type:'multiple_choice', title:'Pick a route', required:true, options:[] }] } });
    assert.equal(created.status(),201);
    let draft = await created.json();
    const blocked = await context.request.post(`${base}/api/forms/${id}/publish`, { headers, data:{} });
    assert.equal(blocked.status(),400); assert.match((await blocked.json()).error,/at least two answers/);
    const unpublished = await context.request.post(`${base}/api/forms/${id}/start`, { headers, data:{} });
    assert.equal(unpublished.status(),404);
    draft.questions[0].options = [{ id:'a', label:'Route A' }, { id:'b', label:'Route B' }];
    const updated = await context.request.put(`${base}/api/forms/${id}`, { headers, data:draft });
    assert.equal(updated.status(),200); draft = await updated.json();
    assert.equal((await context.request.post(`${base}/api/forms/${id}/publish`, { headers, data:{} })).status(),200);
    const start = await context.request.post(`${base}/api/forms/${id}/start`, { headers, data:{} });
    const attempt = await start.json(); assert.equal(start.status(),200);
    const submission = await context.request.post(`${base}/api/forms/${id}/submit`, { headers, data:{ token:attempt.token, answers:{q1:'a'} } });
    assert.equal(submission.status(),200,await submission.text());
    const page = await context.newPage();
    await page.goto(base+'/');
    await page.getByRole('link',{name:'Continue editing: QA Usability Choice',exact:true}).waitFor();
    await page.getByRole('heading',{name:'Your quizzes',exact:true}).waitFor();
    assert.equal(await page.getByRole('heading',{name:'Four ways to start'}).count(),0);
    await page.screenshot({path:path.join(artifacts,'overview-returning.png'),fullPage:false});
    await page.goto(base+'/reports');
    await page.getByRole('searchbox',{name:'Search quiz reports'}).fill(draft.title);
    const row = page.getByRole('listitem').filter({has:page.getByRole('heading',{name:draft.title,exact:true})});
    assert.match(await row.innerText(),/1 response.*Latest response/);
    await row.getByRole('link',{name:'View report',exact:true}).click();
    await page.waitForURL(`${base}/reports/${id}`);
    await page.getByRole('tab',{name:'Responses',exact:true}).click();await page.getByRole('heading',{name:'Responses',exact:true}).waitFor();
    await page.getByText('View answers',{exact:true}).click();
    await page.getByRole('region',{name:'Responses',exact:true}).getByText('Route A',{exact:true}).waitFor();
    assert.equal(await page.getByRole('button',{name:'Publish',exact:true}).count(),0);
    await page.getByRole('searchbox',{name:'Search responses'}).fill('no such answer');
    await page.getByText('Showing 0–0 of 0 matching responses · 1 total',{exact:true}).waitFor();
    await page.getByRole('searchbox',{name:'Search responses'}).fill('');
    await page.getByRole('button',{name:'Refresh responses',exact:true}).click();
    await page.getByText('Showing 1–1 of 1 matching responses · 1 total',{exact:true}).waitFor();
    await page.screenshot({path:path.join(artifacts,'focused-report-desktop.png'),fullPage:false});
    await page.setViewportSize({width:375,height:812});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),true);
    await page.screenshot({path:path.join(artifacts,'focused-report-mobile.png'),fullPage:false});
    await page.setViewportSize({width:1440,height:1000});
    await page.addInitScript(id=>localStorage.setItem('pippi-editor-mode:'+id,'advanced'),id);
    await page.goto(`${base}/editor/${id}`);
    await page.getByRole('textbox',{name:'Quiz name',exact:true}).waitFor();
    const remove = page.locator('button[title="Keep at least two answers"]');
    assert.equal(await remove.count(),2);
    for(const button of await remove.all()) assert.equal(await button.isDisabled(),true);
    draft.questions[0].options = [];
    const incomplete = await context.request.put(`${base}/api/forms/${id}`, {headers,data:draft});
    assert.equal(incomplete.status(),200,'Empty draft still saves after publication');
    const rejected = await context.request.post(`${base}/api/forms/${id}/publish`,{headers,data:{}});
    assert.equal(rejected.status(),400);
    const retained = await context.request.post(`${base}/api/forms/${id}/start`,{headers,data:{}});
    assert.equal((await retained.json()).form.questions[0].options.length,2,'Original live snapshot survives rejection');
    console.log('PASS usability browser acceptance: authenticated reports, unknown-owner 404, API publication gate, saveable drafts, retained public snapshot, returning Overview, live response counts, answer detail/search/refresh, focused mobile report and minimum-answer controls.');
  } finally {
    if(context) await context.request.delete(`${base}/api/forms/${id}`,{headers});
    await browser?.close();
  }
})().catch(error=>{console.error(error);process.exitCode=1;});
